/**
 * @file lib/token_automation.ts
 * @description Dual-column SQLite token store (canonical colour name + packed 24-bit number) that
 * generates the runtime `Bun.markdown.AnsiTheme`, `Bun.markdown.render()` callbacks, a dual-value
 * `.env` profile, and a static TypeScript LUT in one pass.
 *
 * Every write is validated through `Bun.color(name, "number")`; the STRICT table keeps the name,
 * the 24-bit integer and the hex string together so `.env`, the TypeScript LUT, `AnsiTheme` and
 * terminal sessions cannot drift apart.
 */
import { Database } from "bun:sqlite";
import { rename, unlink } from "node:fs/promises";
import { dirname, join } from "node:path";
import { parseColorInput } from "./bun_profiled_terminal.ts";
import { openSportsdeskSqlite } from "./sportsdesk_sqlite.ts";
import {
  BUILTIN_PROFILES,
  deriveColorToken,
  detectColorDepth,
  depthToAnsiFormat,
  type ColorDepth,
  type DerivedColorToken,
  type ProfileInspectSettings,
  type ThemeRole,
} from "./bun_profiled_terminal.ts";

export interface StoredDualColorRow {
  readonly profile: string;
  readonly role: ThemeRole;
  readonly color_name: string;
  readonly color_number: number;
  readonly hex: string;
}

export interface GeneratedProfileBundle {
  readonly profile: string;
  readonly depth: ColorDepth;
  readonly inspect: ProfileInspectSettings;
  readonly tokens: Record<ThemeRole, DerivedColorToken | null>;
  /** Shipped `Bun.markdown.AnsiTheme` (colors, columns, hyperlinks, kittyGraphics, light). */
  readonly ansiTheme: Bun.markdown.AnsiTheme;
  /** Element callbacks for `Bun.markdown.render(md, callbacks, gfmOpts)`. */
  readonly renderCallbacks: Parameters<typeof Bun.markdown.render>[1];
  /** Generated `.env` block storing both `PTY_<ROLE>` (name) and `PTY_<ROLE>_NUMBER` (int). */
  readonly dotEnvText: string;
  /** Generated static TypeScript LUT module with const colour names, numbers and SGR escapes. */
  readonly generatedTsModule: string;
}

const GFM_PARSER_OPTS = {
  tables: true,
  strikethrough: true,
  tasklists: true,
  autolinks: true,
} as const;

const THEME_ROLES: readonly ThemeRole[] = [
  "accent",
  "error",
  "warn",
  "info",
  "muted",
  "code",
  "border",
  "bg",
  "fg",
];

type SettingsRow = {
  console_depth: number;
  sorted: number;
  compact: number;
  max_array_length: number;
};

export const MAX_PROFILE_THEMES = 8;

export class AutomatedDualTokenStore {
  private readonly db: Database;

  constructor(dbPath = ":memory:", seedBuiltins = true) {
    // House rule: SQLite opens only through lib/sportsdesk_sqlite.ts (strict + safeIntegers).
    this.db = openSportsdeskSqlite(dbPath);
    this.db.run("PRAGMA journal_mode = WAL;");
    this.db.run("PRAGMA busy_timeout = 2000;");

    this.db.run(`
      CREATE TABLE IF NOT EXISTS dual_theme_tokens (
        profile TEXT NOT NULL,
        role TEXT NOT NULL,
        color_name TEXT NOT NULL CHECK (length(trim(color_name)) > 0),
        color_number INTEGER NOT NULL CHECK (color_number BETWEEN 0 AND 16777215),
        hex TEXT NOT NULL CHECK (hex LIKE '#______'),
        updated_at INTEGER NOT NULL DEFAULT (unixepoch()),
        PRIMARY KEY (profile, role)
      ) STRICT;
    `);

    this.db.run(`
      CREATE TABLE IF NOT EXISTS profile_settings (
        profile TEXT PRIMARY KEY,
        console_depth INTEGER NOT NULL DEFAULT 2 CHECK (console_depth >= 0),
        sorted INTEGER NOT NULL DEFAULT 0 CHECK (sorted IN (0, 1)),
        compact INTEGER NOT NULL DEFAULT 0 CHECK (compact IN (0, 1)),
        max_array_length INTEGER NOT NULL DEFAULT 100 CHECK (max_array_length >= 0),
        updated_at INTEGER NOT NULL DEFAULT (unixepoch())
      ) STRICT;
    `);

    // color_hex is generated by SQLite so name/int/hex cannot drift inside the DB.
    // `unixepoch('subsec') * 1000` is not a constant default in SQLite, so updated_at_ms is
    // supplied by upsertProfileTheme() rather than declared as a DEFAULT.
    this.db.run(`
      CREATE TABLE IF NOT EXISTS profile_themes (
        profile_id    TEXT    PRIMARY KEY
                              CHECK (length(profile_id) BETWEEN 1 AND 64)
                              CHECK (profile_id GLOB '[a-zA-Z0-9]*')
                              CHECK (profile_id NOT GLOB '*[^a-zA-Z0-9._-]*'),
        color_int     INTEGER NOT NULL
                              CHECK (color_int BETWEEN 0 AND 16777215),
        color_css     TEXT    NOT NULL
                              CHECK (length(color_css) BETWEEN 1 AND 64),
        color_hex     TEXT    GENERATED ALWAYS AS (printf('#%06x', color_int)) STORED,
        color_label   TEXT    NOT NULL
                              CHECK (length(color_label) BETWEEN 1 AND 48)
                              CHECK (color_label NOT GLOB '*[^a-zA-Z0-9_-]*'),
        updated_at_ms INTEGER NOT NULL
      ) STRICT;
    `);

    // The visual cue stops being reliable beyond eight profiles. Enforce the
    // cap in SQLite as well as in the store API so raw seed SQL cannot bypass it.
    this.db.run(`
      CREATE TRIGGER IF NOT EXISTS profile_themes_limit
      BEFORE INSERT ON profile_themes
      WHEN NOT EXISTS (
        SELECT 1 FROM profile_themes WHERE profile_id = NEW.profile_id
      )
      AND (SELECT COUNT(*) FROM profile_themes) >= ${MAX_PROFILE_THEMES}
      BEGIN
        SELECT RAISE(ABORT, 'ERR_TOKEN_PROFILE_LIMIT');
      END;
    `);

    if (seedBuiltins) {
      for (const [name, preset] of Object.entries(BUILTIN_PROFILES)) {
        this.upsertProfile(name, preset.colors, preset.inspect, false);
      }
    }
  }

  /**
   * Validate `colorName` through `Bun.color()` and store the name plus its packed 24-bit number.
   * @throws ERR_COLOR_INVALID when Bun cannot parse the name.
   */
  upsertToken(
    profile: string,
    role: ThemeRole,
    colorName: Bun.ColorInput,
    overwrite = true,
  ): StoredDualColorRow {
    const token = parseColorInput(colorName);
    if (token === null) {
      throw new Error(
        `ERR_COLOR_INVALID: ${JSON.stringify(colorName)} failed Bun.color(..., "number") validation.`,
      );
    }
    // Unsigned 24-bit: no signed 32-bit shift overflow.
    const colorNumber = token.number;
    const normalized = token.name;
    const hex =
      Bun.color(colorNumber, "hex") ??
      `#${colorNumber.toString(16).padStart(6, "0")}`;

    const sql = overwrite
      ? `INSERT INTO dual_theme_tokens (profile, role, color_name, color_number, hex, updated_at)
         VALUES (?1, ?2, ?3, ?4, ?5, unixepoch())
         ON CONFLICT(profile, role) DO UPDATE SET
           color_name = excluded.color_name,
           color_number = excluded.color_number,
           hex = excluded.hex,
           updated_at = unixepoch()`
      : `INSERT OR IGNORE INTO dual_theme_tokens (profile, role, color_name, color_number, hex, updated_at)
         VALUES (?1, ?2, ?3, ?4, ?5, unixepoch())`;

    this.db.query(sql).run(profile, role, normalized, colorNumber, hex);
    return {
      profile,
      role,
      color_name: normalized,
      color_number: colorNumber,
      hex,
    };
  }

  upsertProfile(
    profile: string,
    colors: Partial<Record<ThemeRole, Bun.ColorInput>>,
    inspect?: Partial<ProfileInspectSettings>,
    overwrite = true,
  ): void {
    const settingsSql = overwrite
      ? `INSERT INTO profile_settings (profile, console_depth, sorted, compact, max_array_length, updated_at)
         VALUES (?1, ?2, ?3, ?4, ?5, unixepoch())
         ON CONFLICT(profile) DO UPDATE SET
           console_depth = excluded.console_depth,
           sorted = excluded.sorted,
           compact = excluded.compact,
           max_array_length = excluded.max_array_length,
           updated_at = unixepoch()`
      : `INSERT OR IGNORE INTO profile_settings (profile, console_depth, sorted, compact, max_array_length, updated_at)
         VALUES (?1, ?2, ?3, ?4, ?5, unixepoch())`;

    const transaction = this.db.transaction(() => {
      for (const [role, name] of Object.entries(colors)) {
        if (name) this.upsertToken(profile, role as ThemeRole, name, overwrite);
      }
      if (inspect) {
        const depth = inspect.consoleDepth ?? 2;
        this.db
          .query(settingsSql)
          .run(
            profile,
            depth === Number.POSITIVE_INFINITY ? 999_999 : depth,
            inspect.sorted ? 1 : 0,
            inspect.compact ? 1 : 0,
            inspect.maxArrayLength ?? 100,
          );
      }
    });
    transaction();
  }

  getRows(profile: string): StoredDualColorRow[] {
    return this.db
      .query(
        `SELECT profile, role, color_name, color_number, hex
         FROM dual_theme_tokens WHERE profile = ?1 ORDER BY role`,
      )
      .all(profile)
      .map((row) => {
        // `safeIntegers` returns bigint; the row contract is a number.
        const stored = row as StoredDualColorRow & {
          color_number: number | bigint;
        };
        return { ...stored, color_number: Number(stored.color_number) };
      });
  }

  getInspect(profile: string): ProfileInspectSettings {
    const row = this.db
      .query(
        `SELECT console_depth, sorted, compact, max_array_length
         FROM profile_settings WHERE profile = ?1`,
      )
      .get(profile) as SettingsRow | null;

    if (row === null) {
      return {
        consoleDepth: 2,
        sorted: false,
        compact: false,
        maxArrayLength: 100,
      };
    }
    return {
      consoleDepth:
        Number(row.console_depth) >= 999_999
          ? Number.POSITIVE_INFINITY
          : Number(row.console_depth),
      sorted: Number(row.sorted) === 1,
      compact: Number(row.compact) === 1,
      maxArrayLength: Number(row.max_array_length),
    };
  }

  listProfiles(): string[] {
    return this.db
      .query("SELECT DISTINCT profile FROM dual_theme_tokens ORDER BY profile")
      .all()
      .map((row) => (row as { profile: string }).profile);
  }

  /** Upsert one registry row; color_hex is produced by SQLite, never supplied by the caller. */
  upsertProfileTheme(row: RegistryColorRow): void {
    const profileId = assertProfileId(row.profile_id);
    const colorInt = assertRgb24(row.color_int);
    const existing = this.db
      .query("SELECT 1 FROM profile_themes WHERE profile_id = ?1")
      .get(profileId);
    if (existing === null) {
      const countRow = this.db
        .query("SELECT COUNT(*) AS count FROM profile_themes")
        .get() as { count: number | bigint };
      if (Number(countRow.count) >= MAX_PROFILE_THEMES) {
        const error = new Error(
          "ERR_TOKEN_PROFILE_LIMIT: refusing profile " +
            profileId +
            "; limit is " +
            MAX_PROFILE_THEMES,
        ) as Error & { code: "ERR_TOKEN_PROFILE_LIMIT" };
        error.code = "ERR_TOKEN_PROFILE_LIMIT";
        throw error;
      }
    }
    if (Bun.color(row.color_css, "number") !== colorInt) {
      const error = new Error(
        `ERR_TOKEN_CSS_DRIFT: ${profileId} color_css=${row.color_css} does not match color_int=${colorInt}`,
      ) as Error & { code: "ERR_TOKEN_CSS_DRIFT" };
      error.code = "ERR_TOKEN_CSS_DRIFT";
      throw error;
    }
    this.db
      .query(
        `INSERT INTO profile_themes
           (profile_id, color_int, color_css, color_label, updated_at_ms)
         VALUES (?1, ?2, ?3, ?4, ?5)
         ON CONFLICT(profile_id) DO UPDATE SET
           color_int = excluded.color_int,
           color_css = excluded.color_css,
           color_label = excluded.color_label,
           updated_at_ms = excluded.updated_at_ms`,
      )
      .run(profileId, colorInt, row.color_css, row.color_label, Date.now());
  }

  /** Rows in the canonical emission order; integers are converted from safeIntegers BigInts. */
  listProfileThemes(): RegistryColorRow[] {
    const rows = this.db
      .query(
        `SELECT profile_id, color_int, color_css, color_hex, color_label
         FROM profile_themes ORDER BY profile_id ASC`,
      )
      .all() as Array<Record<string, string | bigint | number>>;
    return rows.map((row) => ({
      profile_id: assertProfileId(String(row.profile_id)),
      color_int: assertRgb24(Number(row.color_int)),
      color_css: String(row.color_css),
      color_hex: String(row.color_hex),
      color_label: String(row.color_label),
    }));
  }

  /** Generate the runtime theme, `AnsiTheme`, dual-value `.env` and TypeScript LUT for one profile. */
  generateBundle(
    profile: string,
    options?: {
      env?: Record<string, string | undefined>;
      isTTY?: boolean;
      columns?: number;
    },
  ): GeneratedProfileBundle {
    const rows = this.getRows(profile);
    if (rows.length === 0) {
      throw new Error(
        `ERR_PROFILE_NOT_FOUND: Profile "${profile}" has no stored tokens.`,
      );
    }

    const mergedEnv: Record<string, string> = {};
    for (const [key, value] of Object.entries({
      ...process.env,
      ...options?.env,
    })) {
      if (value !== undefined) mergedEnv[key] = value;
    }

    const isTTY = options?.isTTY ?? Boolean(process.stdout.isTTY);
    const depth = detectColorDepth(mergedEnv, isTTY);
    const ansiFormat = depthToAnsiFormat(depth);
    const inspect = this.getInspect(profile);

    const rowByRole = new Map(rows.map((row) => [row.role, row]));
    const tokens = {} as Record<ThemeRole, DerivedColorToken | null>;
    for (const role of THEME_ROLES) {
      const stored = rowByRole.get(role);
      tokens[role] = stored
        ? deriveColorToken(role, stored.color_name, ansiFormat)
        : null;
    }

    // 1. Shipped AnsiTheme, derived from the stored tokens and the detected depth.
    const colorsEnabled = depth !== "none";
    const ansiTheme: Bun.markdown.AnsiTheme = {
      colors: colorsEnabled,
      columns: options?.columns ?? process.stdout.columns ?? 80,
      hyperlinks: colorsEnabled && isTTY,
      kittyGraphics:
        colorsEnabled &&
        isTTY &&
        Boolean(
          mergedEnv.KITTY_WINDOW_ID ??
          /kitty|wezterm|ghostty/i.test(
            `${mergedEnv.TERM ?? ""} ${mergedEnv.TERM_PROGRAM ?? ""}`,
          ),
        ),
      ...(tokens.bg ? { light: tokens.bg.luminance > 0.5 } : {}),
    };

    // 2. Element callbacks for Bun.markdown.render(), using the stored SGR escapes.
    const accent =
      tokens.accent ?? deriveColorToken("accent", "dodgerblue", ansiFormat);
    const info = tokens.info ?? accent;
    const warn = tokens.warn ?? accent;
    const code = tokens.code ?? accent;
    const muted = tokens.muted ?? accent;

    const renderCallbacks: Parameters<typeof Bun.markdown.render>[1] =
      colorsEnabled
        ? {
            heading: (content, { level }) =>
              `\n\x1b[1m${level === 1 ? accent.ansiFg : info.ansiFg}${"#".repeat(level)} ${content}\x1b[0m\n`,
            strong: (content) => `\x1b[1m${warn.ansiFg}${content}\x1b[0m`,
            codespan: (content) => `${code.ansiFg}\`${content}\`\x1b[39m`,
            link: (content, { href }) =>
              ansiTheme.hyperlinks && href
                ? `\x1b]8;;${href}\x07${accent.ansiFg}\x1b[4m${content}\x1b[24m\x1b[39m\x1b]8;;\x07`
                : `${accent.ansiFg}${content}\x1b[39m ${muted.ansiFg}(${href})\x1b[39m`,
          }
        : {};

    // 3. Dual-value .env: name + 24-bit integer, with expansion for repeated colours.
    const depthText =
      inspect.consoleDepth === Number.POSITIVE_INFINITY
        ? "Infinity"
        : String(inspect.consoleDepth);
    const envLines: string[] = [
      `# Auto-generated dual-token profile: ${profile}`,
      `PTY_PROFILE="${profile}"`,
      `PTY_CONSOLE_DEPTH="${depthText}"`,
      ...(Number.isFinite(inspect.consoleDepth)
        ? [`BUN_OPTIONS="--console-depth=${inspect.consoleDepth}"`]
        : []),
    ];

    const seenColorVar = new Map<string, string>();
    for (const row of rows) {
      const baseKey = `PTY_${row.role.toUpperCase()}`;
      const existing = seenColorVar.get(row.color_name);
      if (existing !== undefined) {
        envLines.push(`${baseKey}=$${existing}`);
        envLines.push(`${baseKey}_NUMBER=$${existing}_NUMBER`);
      } else {
        envLines.push(`${baseKey}="${row.color_name}"`);
        envLines.push(`${baseKey}_NUMBER=${row.color_number}`);
        seenColorVar.set(row.color_name, baseKey);
      }
    }

    // 4. Static TypeScript LUT: SGR escapes are precomputed at generation time.
    const tokenEntries = rows
      .map((row) => {
        const sgr16m = JSON.stringify(
          Bun.color(row.color_number, "ansi-16m") ?? "",
        );
        const sgr256 = JSON.stringify(
          Bun.color(row.color_number, "ansi-256") ?? "",
        );
        return `    ${row.role}: { name: ${JSON.stringify(row.color_name)}, number: 0x${row.color_number
          .toString(16)
          .padStart(
            6,
            "0",
          )}, hex: ${JSON.stringify(row.hex)}, ansi16m: ${sgr16m}, ansi256: ${sgr256} }`;
      })
      .join(",\n");

    const constName = `GENERATED_PROFILE_${profile.replace(/[^a-zA-Z0-9]/g, "_").toUpperCase()}`;
    const generatedTsModule = [
      `// AUTO-GENERATED BY token_automation.ts — DO NOT EDIT MANUALLY`,
      `export const ${constName} = {`,
      `  profile: ${JSON.stringify(profile)},`,
      `  consoleDepth: ${inspect.consoleDepth === Number.POSITIVE_INFINITY ? "Infinity" : inspect.consoleDepth},`,
      `  ansiTheme: ${JSON.stringify(ansiTheme)},`,
      `  tokens: {`,
      tokenEntries,
      `  },`,
      `} as const;\n`,
    ].join("\n");

    return {
      profile,
      depth,
      inspect,
      tokens,
      ansiTheme,
      renderCallbacks,
      dotEnvText: `${envLines.join("\n")}\n`,
      generatedTsModule,
    };
  }

  /** Write `.env.<profile>` and `<profile>.theme.gen.ts` into `outDir`. */
  async emitArtifacts(
    profile: string,
    outDir: string,
    options?: { env?: Record<string, string | undefined>; isTTY?: boolean },
  ): Promise<{
    envFile: string;
    tsFile: string;
    bundle: GeneratedProfileBundle;
  }> {
    const bundle = this.generateBundle(profile, options);
    const envFile = `${outDir}/.env.${profile}`;
    const tsFile = `${outDir}/${profile}.theme.gen.ts`;

    // Bun.write creates missing parent directories (0755), so no node:fs mkdir is needed.
    await Promise.all([
      Bun.write(envFile, bundle.dotEnvText),
      Bun.write(tsFile, bundle.generatedTsModule),
    ]);

    return { envFile, tsFile, bundle };
  }

  renderMarkdown(
    markdown: string,
    bundle: GeneratedProfileBundle,
    mode: "native" | "themed" = "themed",
  ): string {
    if (mode === "native" || bundle.depth === "none") {
      return Bun.markdown.ansi(markdown, bundle.ansiTheme);
    }
    // trusted-markdown: terminal output via pre-baked ANSI callbacks; never a DOM sink.
    return Bun.markdown.render(
      markdown,
      bundle.renderCallbacks,
      GFM_PARSER_OPTS,
    );
  }

  close(): void {
    this.db.close();
  }
}

/**
 * `codegen` subcommand body: emit both artifacts for one profile and print a short summary.
 *
 * Kept as a function because this repo has no `profile-cli.ts`; wire it into whatever CLI owns
 * profile management. Accepts flags (`--profile X --out-dir Y`) or the positional form.
 * @param dbPath - SQLite file the dual-token store lives in.
 * @param args - subcommand arguments after `codegen`.
 * @returns process exit code: 0 written, 2 unknown profile, 1 failure.
 */
export async function runCodegenSubcommand(
  dbPath: string,
  args: string[],
): Promise<number> {
  let profileFlag: string | undefined;
  let outDirFlag: string | undefined;
  const positional: string[] = [];
  for (let index = 0; index < args.length; index++) {
    const arg = args[index]!;
    if (arg === "--profile") profileFlag = args[++index];
    else if (arg.startsWith("--profile="))
      profileFlag = arg.slice("--profile=".length);
    else if (arg === "--out-dir") outDirFlag = args[++index];
    else if (arg.startsWith("--out-dir="))
      outDirFlag = arg.slice("--out-dir=".length);
    else if (!arg.startsWith("--")) positional.push(arg);
  }
  const profile =
    profileFlag ?? positional[0] ?? Bun.env.PTY_PROFILE ?? "default";
  const outDir = outDirFlag ?? positional[1] ?? "./generated";

  const store = new AutomatedDualTokenStore(dbPath, true);
  try {
    if (!store.listProfiles().includes(profile)) {
      console.error(`ERR_PROFILE_NOT_FOUND: "${profile}"`);
      return 2;
    }
    const { envFile, tsFile, bundle } = await store.emitArtifacts(
      profile,
      outDir,
      { isTTY: true },
    );
    process.stdout.write(
      store.renderMarkdown(
        `# Generated \`${profile}\`\n- Env: \`${envFile}\`\n- Theme LUT: \`${tsFile}\`\n- Console Depth: **${bundle.inspect.consoleDepth}**`,
        bundle,
      ),
    );
    return 0;
  } finally {
    store.close();
  }
}

/** Branded profile id; only `assertProfileId` may mint one. */
export type ProfileId = string & { readonly __brand: "ProfileId" };

export interface RegistryColorRow {
  readonly profile_id: ProfileId;
  /** 24-bit 0xRRGGBB from `Bun.color(raw, "number")`. */
  readonly color_int: number;
  /** Canonical CSS from `Bun.color(raw, "css")`. */
  readonly color_css: string;
  /** SQLite-generated `#rrggbb`; never supplied by a caller. */
  readonly color_hex: string;
  /** Human alias, e.g. `sky-400`. */
  readonly color_label: string;
}

const PROFILE_ID_RE = /^[a-zA-Z0-9][a-zA-Z0-9._-]{0,63}$/;
const LABEL_RE = /^[a-zA-Z0-9_-]{1,48}$/;

export function assertProfileId(raw: string): ProfileId {
  if (!PROFILE_ID_RE.test(raw)) {
    throw new TypeError(`ERR_TOKEN_PROFILE_ID: invalid ProfileId "${raw}"`);
  }
  return raw as ProfileId;
}

export function assertRgb24(colorInt: number): number {
  if (!Number.isInteger(colorInt) || colorInt < 0 || colorInt > 0xffffff) {
    throw new RangeError(
      `ERR_TOKEN_RGB24: expected 0..0xffffff, got ${colorInt}`,
    );
  }
  return colorInt;
}

export function normalizeColorInput(
  raw: string,
  label?: string,
): Omit<RegistryColorRow, "profile_id" | "color_hex"> {
  const colorInt = Bun.color(raw.trim().toLowerCase(), "number");
  const colorCss = Bun.color(raw.trim().toLowerCase(), "css");
  if (colorInt === null || colorCss === null) {
    throw new TypeError(`ERR_TOKEN_COLOR_INVALID: cannot parse "${raw}"`);
  }
  const colorLabel = (label ?? colorCss)
    .replace(/[^a-zA-Z0-9_-]+/g, "-")
    .replace(/^-+|-+$/g, "");
  if (!LABEL_RE.test(colorLabel)) {
    throw new TypeError(`ERR_TOKEN_LABEL_INVALID: "${colorLabel}"`);
  }
  return {
    color_int: assertRgb24(colorInt),
    color_css: colorCss,
    color_label: colorLabel,
  };
}

export function toEnvSlug(profileId: ProfileId): string {
  return profileId
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

/** Escape the characters that can break or inject into a quoted .env value. */
export function sanitizeEnvValue(value: string): string {
  return value.replace(/[\\"$`\r\n]/g, (ch) =>
    ch === "\r" || ch === "\n" ? "" : `\\${ch}`,
  );
}

/** Fingerprint the canonical, sorted snapshot; unrelated SQLite writes do not change it. */
export function computeSnapshotFingerprint(
  rows: readonly RegistryColorRow[],
): string {
  const hasher = new Bun.CryptoHasher("sha256");
  const canonical = [...rows].sort((a, b) =>
    a.profile_id.localeCompare(b.profile_id),
  );
  for (const row of canonical) {
    hasher.update(
      `${row.profile_id}\0${row.color_int}\0${row.color_css}\0${row.color_label}\n`,
    );
  }
  return hasher.digest("hex");
}

export function assertNoSlugCollisions(
  rows: readonly RegistryColorRow[],
): void {
  const seen = new Map<string, ProfileId>();
  for (const row of rows) {
    const slug = toEnvSlug(row.profile_id);
    const previous = seen.get(slug);
    if (previous !== undefined && previous !== row.profile_id) {
      const error = new Error(
        `ERR_TOKEN_SLUG_COLLISION: "${previous}" and "${row.profile_id}" both map to PROFILE_${slug}_*`,
      ) as Error & { code: "ERR_TOKEN_SLUG_COLLISION" };
      error.code = "ERR_TOKEN_SLUG_COLLISION";
      throw error;
    }
    seen.set(slug, row.profile_id);
  }
}

function canonicalRows(rows: readonly RegistryColorRow[]): RegistryColorRow[] {
  return [...rows].sort((a, b) => a.profile_id.localeCompare(b.profile_id));
}

/**
 * Committed example contract: the profile keys are present, but live values are
 * redacted. Copy .env for machine-local values; .env.example must never contain
 * a live override from the registry.
 */
export function renderEnvExampleFile(
  rows: readonly RegistryColorRow[],
  fingerprint: string,
): string {
  assertNoSlugCollisions(rows);
  const lines = [
    `# Auto-generated by token-watch-daemon.ts (sha256: ${fingerprint})`,
    `# Mode: example | Keys only; values are placeholders. Copy to .env for live values.`,
    ``,
  ];
  for (const row of canonicalRows(rows)) {
    const key = toEnvSlug(row.profile_id);
    lines.push(
      `# profile_id=${row.profile_id}`,
      `PROFILE_${key}_COLOR_LABEL="<label>"`,
      `PROFILE_${key}_COLOR_CSS="<css>"`,
      `PROFILE_${key}_COLOR_INT=0`,
      `PROFILE_${key}_COLOR_HEX="#000000"`,
      ``,
    );
  }
  return lines.join("\n");
}

/** Shared renderer for live .env; the example contract is redacted. */
export function renderEnvFile(
  rows: readonly RegistryColorRow[],
  fingerprint: string,
  mode: "live" | "example" = "live",
): string {
  assertNoSlugCollisions(rows);
  if (mode === "example") return renderEnvExampleFile(rows, fingerprint);

  const lines = [
    `# Auto-generated by token-watch-daemon.ts (sha256: ${fingerprint})`,
    `# Mode: live | Do not edit manually; source of truth is SQLite profile_themes`,
    ``,
  ];
  for (const row of canonicalRows(rows)) {
    const rgb = assertRgb24(row.color_int);
    const hex = `#${rgb.toString(16).padStart(6, "0")}`;
    if (row.color_hex !== hex) {
      throw new Error(
        `ERR_TOKEN_HEX_DRIFT: ${row.profile_id} has ${row.color_hex}, expected ${hex}`,
      );
    }
    const key = toEnvSlug(row.profile_id);
    lines.push(
      `# profile_id=${row.profile_id}`,
      `PROFILE_${key}_COLOR_LABEL="${sanitizeEnvValue(row.color_label)}"`,
      `PROFILE_${key}_COLOR_CSS="${sanitizeEnvValue(row.color_css)}"`,
      `PROFILE_${key}_COLOR_INT=${rgb}`,
      `PROFILE_${key}_COLOR_HEX="${hex}"`,
      ``,
    );
  }
  return lines.join("\n");
}

/** Pre-bake every ANSI escape so `[Bun.inspect.custom]` never calls Bun.color at runtime. */
export function renderThemeGenTs(
  rows: readonly RegistryColorRow[],
  fingerprint: string,
): string {
  assertNoSlugCollisions(rows);
  const entries = canonicalRows(rows).map((row) => {
    const rgb = assertRgb24(row.color_int);
    const r = (rgb >> 16) & 0xff;
    const g = (rgb >> 8) & 0xff;
    const b = rgb & 0xff;
    const hex = `#${rgb.toString(16).padStart(6, "0")}`;
    if (row.color_hex !== hex) {
      throw new Error(
        `ERR_TOKEN_HEX_DRIFT: ${row.profile_id} has ${row.color_hex}, expected ${hex}`,
      );
    }
    return (
      `  ${JSON.stringify(row.profile_id)}: Object.freeze({\n` +
      `    colorInt: ${rgb},\n` +
      `    colorCss: ${JSON.stringify(row.color_css)},\n` +
      `    colorHex: ${JSON.stringify(hex)},\n` +
      `    colorLabel: ${JSON.stringify(row.color_label)},\n` +
      `    rgb: Object.freeze([${r}, ${g}, ${b}] as const),\n` +
      `    ansi16: ${JSON.stringify(Bun.color(rgb, "ansi-16") ?? "")},\n` +
      `    ansi256: ${JSON.stringify(Bun.color(rgb, "ansi-256") ?? "")},\n` +
      `    ansi16m: ${JSON.stringify(Bun.color(rgb, "ansi-16m") ?? "")},\n` +
      `  }),`
    );
  });
  return [
    `// Auto-generated by token-watch-daemon.ts (sha256: ${fingerprint})`,
    `import type { ProfileId } from "./token_automation";`,
    ``,
    `export const THEME_SNAPSHOT_SHA256 = ${JSON.stringify(fingerprint)} as const;`,
    ``,
    `export interface ProfileThemeEntry {`,
    `  readonly colorInt: number;`,
    `  readonly colorCss: string;`,
    `  readonly colorHex: string;`,
    `  readonly colorLabel: string;`,
    `  readonly rgb: readonly [number, number, number];`,
    `  readonly ansi16: string;`,
    `  readonly ansi256: string;`,
    `  readonly ansi16m: string;`,
    `}`,
    ``,
    `export const PROFILE_THEME_LUT: Readonly<Record<ProfileId, ProfileThemeEntry>> = Object.freeze({`,
    ...entries,
    `} as Record<ProfileId, ProfileThemeEntry>);`,
    ``,
  ].join("\n");
}

/** Write to a sibling temp file, then rename; a failure leaves no partial target. */
export async function atomicWrite(
  targetPath: string,
  content: string,
): Promise<void> {
  const tmpPath = join(
    dirname(targetPath),
    `.${process.pid}.${Bun.nanoseconds()}.tmp`,
  );
  try {
    await Bun.write(tmpPath, content);
    await rename(tmpPath, targetPath);
  } catch (error) {
    await unlink(tmpPath).catch(() => {});
    throw error;
  }
}
